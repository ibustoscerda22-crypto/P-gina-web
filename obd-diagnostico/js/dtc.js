const HIGH = new Set(['P0217', 'P0219', 'P0300', 'P0301', 'P0302', 'P0303', 'P0304', 'P0524', 'P0335', 'P0016', 'P0087', 'P0230', 'P2100', 'P2101', 'P2135', 'U0100']);
const LOW = /^P04(4|5)\d|^P046\d|^P053\d/;

function familyOf(code) {
  const s = code[0];
  if (s === 'B') return 'Carrocería (luces, cierres, airbags, climatización)';
  if (s === 'C') return 'Chasis (frenos ABS, dirección, suspensión)';
  if (s === 'U') return 'Red de comunicación entre módulos';
  if (code[1] !== '0' && code[1] !== '2') return 'Código específico del fabricante (GM): requiere manual de servicio';
  const fam = {
    0: 'Medición de aire y combustible / emisiones auxiliares',
    1: 'Medición de aire y combustible',
    2: 'Medición de aire y combustible (inyectores)',
    3: 'Sistema de encendido o fallo de encendido',
    4: 'Controles auxiliares de emisiones',
    5: 'Velocidad del vehículo, ralentí y entradas auxiliares',
    6: 'Computador del motor (ECU) y salidas auxiliares',
    7: 'Transmisión',
    8: 'Transmisión',
    9: 'Transmisión',
    A: 'Propulsión híbrida',
  };
  return fam[code[2]] || 'Tren motriz';
}

export function describeDtc(code) {
  const severity = HIGH.has(code) ? 'alta' : LOW.test(code) ? 'baja' : 'media';
  return {
    code,
    description: D[code] || familyOf(code),
    known: !!D[code],
    family: familyOf(code),
    causes: CAUSES[code] || [],
    severity,
  };
}
