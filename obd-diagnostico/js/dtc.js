// Decodificación y descripción en español de códigos de falla OBD-II (DTC).

export function decodeDtc(hex) {
  const b = parseInt(hex.slice(0, 2), 16);
  return 'PCBU'[b >> 6] + ((b >> 4) & 3) + hex[1] + hex.slice(2);
}

